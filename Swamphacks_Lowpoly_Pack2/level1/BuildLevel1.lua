			warn(string.format("%s imported at %.2fx the expected size; re-import with meter units", name, ratio))
		end
		template.WorldPivot = CFrame.new(cf.Position + info[1])
	end
end

local old = workspace:FindFirstChild("Level1")
if old then old:Destroy() end
local level = Instance.new("Model")
level.Name = "Level1"
local folders = {}
local prepared = {}
for _, e in ipairs(PLACE) do
	local name = e[1]
	local template = assets:FindFirstChild(name)
	if not template then
		warn("Missing asset in ServerStorage.LowpolyAssets: " .. name)
	else
		if not prepared[name] then prepare(template, name); prepared[name] = true end
		local folder = folders[name]
		if not folder then
			folder = Instance.new("Folder")
			folder.Name = name
			folder.Parent = level
			folders[name] = folder
		end
		local m = template:Clone()
		m:PivotTo(CFrame.new(e[2] * S, e[4] * S, -e[3] * S) * CFrame.Angles(0, math.rad(e[5]), 0))
		for _, p in ipairs(m:GetDescendants()) do
			if p:IsA("BasePart") then p.Anchored = true end
		end
		m.Parent = folder
	end
end
level.Parent = workspace
local spawnCar = folders["Car_Red"] and folders["Car_Red"]:GetChildren()[1]
if spawnCar then
	local sp = workspace:FindFirstChildOfClass("SpawnLocation") or Instance.new("SpawnLocation")
	sp.Anchored = true
	sp.Size = Vector3.new(8, 1, 8)
	sp.CFrame = spawnCar:GetPivot() * CFrame.new(11, 1.6, 0)
	sp.Parent = workspace
end
